    // script para procesar el formulario con AJAX
    document.addEventListener('DOMContentLoaded', function () {
      const contactForm = document.getElementById('contactForm');
      const formResult = document.getElementById('form-result');
      const successModal = new bootstrap.Modal(document.getElementById('successModal'));

      // 1. Interceptar el envío del formulario
      contactForm.addEventListener('submit', function (e) {
        e.preventDefault();

        // Limpiar mensajes previos
        formResult.innerHTML = '';

        // Mostrar un loader simple (opcional)
        formResult.innerHTML = '<div class="alert alert-info text-center">Enviando mensaje...</div>';

        const formData = new FormData(contactForm);

        // 2. Enviar la solicitud vía AJAX
        fetch(contactForm.getAttribute('action'), {
          method: 'POST',
          body: formData
        })
          .then(response => {
            // PHPMailer está imprimiendo el debug antes del JSON, hay que limpiarlo
            return response.text().then(text => {
              // Buscar el inicio del JSON
              const jsonStart = text.indexOf('{');
              if (jsonStart !== -1) {
                return JSON.parse(text.substring(jsonStart));
              }
              throw new Error('Respuesta del servidor no válida (No se encontró JSON).');
            });
          })
          .then(data => {
            // 3. Manejar la respuesta JSON
            if (data.status === 'success') {
              // Ocultar mensaje de proceso
              formResult.innerHTML = '';

              // Mostrar el modal de éxito
              successModal.show();

              // Opcional: limpiar el formulario después del éxito
              contactForm.reset();

            } else {
              // Mostrar mensaje de error en la página
              formResult.innerHTML = '<div class="alert alert-danger">' + (data.message || 'Error desconocido al enviar el formulario.') + '</div>';
            }
          })
          .catch(error => {
            // 4. Manejar errores de red/parseo
            console.error('Error al procesar la solicitud:', error);
            formResult.innerHTML = '<div class="alert alert-danger">Error de conexión. Por favor, revisa la consola o inténtalo más tarde.</div>';
          });
      });
    });
  </script>



